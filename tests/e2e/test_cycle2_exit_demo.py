"""Cycle 2 exit demo with NEUTRAL specs (no client project). Needs Docker (testcontainers Postgres).

1. Invoice approval + a weekly (cron) job + an outbound webhook to a FAKE ERP receiver. The receiver is a real
   local TCP/HTTP server (started inside the scenario) that fails the first 2 deliveries of every webhook id with
   HTTP 503, then answers 200; it verifies the HMAC signature of every try. The delivery log and the attempt log
   are read back through the admin API.
2. HR leave request whose approval transition sends an e-mail through the notifications block. The only provider
   is the platform's emulator: nothing leaves the process.

Both specs are built here from the example fixtures plus the Cycle 2 blocks, validated by the Spec model and
generated by the real generator. The scenario files below are written into the generated project and run there
against a real Postgres (the same pattern as test_cycle1_demo.py). Set CYCLE2_DEMO_OUT=<file> to keep the
transcript. The SSRF guard stays ON in the demo: a name is resolved to a (fake) public address, and only the
connector is pointed at the local receiver, which is the hook the generated tests use too."""

