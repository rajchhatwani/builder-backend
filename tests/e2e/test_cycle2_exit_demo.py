def run_demo(name: str, spec_data: dict[str, Any], scenario: str, owner: dict[str, str], hook: tuple[str, str],
             postgres: PostgresContainer, tmp_path_factory) -> list[str]:  # noqa: ANN001, F811
    Spec.model_validate(spec_data)  # the spec objects, validated like the builder API does
    out = [f"## {name}", ""]
    root = write_project(tmp_path_factory.mktemp(name), generate_tree(spec_data))
    out.append(f"spec valid; generated {sum(1 for p in root.rglob('*') if p.is_file())} files")
    write_body(root, hook[0], hook[1])
    for path, text in owner.items():
        (root / path).write_text(text, encoding="utf-8")
    code, report, summary = run_gate(root)
    assert code == 0 and report["ok"] is True, (report.get("findings"), summary)
    out.append("hook gate: exit 0")
    url = db_url(postgres, f"{name}_test")
    migrate(root, url)
    out.append("migrate: upgrade, alembic check, downgrade, upgrade: all exit 0")
    (root / "tests" / "test_exit_demo.py").write_text(scenario, encoding="utf-8")
    result = run(["-m", "pytest", "-q", "-p", "no:cacheprovider", "tests/test_exit_demo.py"], root, url)
    log = (root / "demo_transcript.log").read_text(encoding="utf-8") if (root / "demo_transcript.log").exists() else ""
    print("\n".join(["", f"===== {name} =====", log, result.stdout[-1500:]]))
    story = counts(ok(result))
    assert "failed" not in story
    out += [f"scenarios: {story}", "", "```", *[line for line in log.splitlines() if line.strip()], "```", ""]
    return out


def keep(lines: list[str], name: str) -> None:
    target = os.environ.get("CYCLE2_DEMO_OUT")
    if target:
        Path(f"{target}.{name}.part").write_text("\n".join(lines) + "\n", encoding="utf-8")


